test('retry after a lost create response reuses the key and creates one history event', async ({ page }) => {
  const keys: string[] = []
  let loseResponse = true
  await page.route('**/api/v1/pricing-exceptions', async route => {
    if (route.request().method() !== 'POST') { await route.continue(); return }
    keys.push(route.request().headers()['idempotency-key'])
    if (loseResponse) {
      loseResponse = false
      const response = await route.fetch()
      expect(response.status()).toBe(201)
      await response.dispose()
      await route.abort('failed')
    } else { await route.continue() }
  })
  await page.goto('/')
  await page.getByRole('button', { name: 'New request', exact: true }).click()
  await page.getByLabel('Assigned reviewer').selectOption('22222222-2222-2222-2222-222222222222')
  await page.getByLabel('Mortgage application ID').fill(crypto.randomUUID())
  await page.getByLabel('Requested discount').fill('35')
  await page.getByLabel('Supporting reason').fill('Lost response retry verification.')
  await page.getByRole('button', { name: 'Submit request', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Unable to connect')
  await page.getByRole('button', { name: 'Submit request', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  expect(keys).toHaveLength(2)
  expect(keys[0]).toBeTruthy()
  expect(keys[0]).toBe(keys[1])
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await page.getByRole('button', { name: /^History/ }).click()
  await expect(page.locator('.timeline li')).toHaveCount(1)
})

