import { test, expect } from '@playwright/test'

test('reviewer can decline a request and preserve its decision in history', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'New request', exact: true }).click()
  await page.getByLabel('Mortgage application ID').fill(crypto.randomUUID())
  await page.getByLabel('Requested discount').fill('40')
  await page.getByLabel('Supporting reason').fill('A proposal requiring independent review.')
  await page.getByRole('button', { name: 'Submit request', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.getByLabel('Demo role').selectOption('22222222-2222-2222-2222-222222222222')
  await page.getByRole('button', { name: 'Review request', exact: true }).click()
  await page.getByRole('radio', { name: /Decline/ }).check()
  await page.getByLabel('Review note').fill('Insufficient supporting justification.')
  await page.getByRole('button', { name: 'Confirm decline', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'Declined', exact: true })).toBeVisible()
  await page.getByRole('button', { name: /^History/ }).click()
  await expect(page.getByText('Request declined', { exact: true })).toBeVisible()
  await expect(page.getByText('“Insufficient supporting justification.”')).toBeVisible()
})

test('manager, reviewer and mortgage process complete an exception workflow', async ({ page }) => {
  const applicationId = crypto.randomUUID()
  const consoleErrors: string[] = []
  page.on('pageerror', error => consoleErrors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Pricing exceptions', exact: true })).toBeVisible()
  await expect(page.getByText('API connected')).toBeVisible()
  await page.getByRole('button', { name: 'New request', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Mortgage application ID').fill(applicationId)
  await dialog.getByLabel('Requested discount').fill('50')
  await dialog.getByLabel('Supporting reason').fill('Competitive offer for an existing mortgage application.')
  await dialog.getByRole('button', { name: 'Submit request', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('cell', { name: 'Pending review' })).toBeVisible()
  await expect(page.getByRole('heading', { name: /^PE-/ })).toBeVisible()
  await page.getByLabel('Demo role').selectOption('22222222-2222-2222-2222-222222222222')
  await page.getByRole('button', { name: 'Review request', exact: true }).click()
  await expect(page.getByRole('dialog').getByText('Competitive offer for an existing mortgage application.')).toBeVisible()
  await page.getByLabel('Review note').fill('Accepted after independent review.')
  await page.getByRole('button', { name: 'Confirm approval', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'Approved', exact: true })).toBeVisible()

  await page.getByLabel('Demo role').selectOption('33333333-3333-3333-3333-333333333333')
  await page.getByRole('button', { name: 'Approved discounts', exact: true }).click()
  await page.getByLabel('Mortgage application ID').fill(applicationId)
  await page.getByRole('button', { name: 'Find approved discount', exact: true }).click()
  await expect(page.getByText('Currently approved', { exact: true })).toBeVisible()
  await expect(page.getByText('0.50% reduction from the standard rate')).toBeVisible()
  await page.getByRole('button', { name: 'View request and history', exact: true }).click()

  await page.getByLabel('Demo role').selectOption('11111111-1111-1111-1111-111111111111')
  await page.getByRole('button', { name: 'Submit a revision', exact: true }).click()
  await expect(page.getByText('Submitting this revision withdraws the current approval until the new terms are approved.')).toBeVisible()
  await page.getByLabel('Requested discount').fill('75')
  await page.getByLabel('Supporting reason').fill('Updated competitive offer.')
  await page.getByRole('button', { name: 'Submit revision', exact: true }).click()
  await expect(page.getByRole('cell', { name: 'Pending review' })).toBeVisible()
  await page.getByRole('button', { name: /^History/ }).click()
  await expect(page.getByText('New revision submitted', { exact: true })).toBeVisible()
  await expect(page.getByText('Request approved', { exact: true })).toBeVisible()

  await page.getByLabel('Demo role').selectOption('33333333-3333-3333-3333-333333333333')
  await page.getByRole('button', { name: 'Approved discounts', exact: true }).click()
  await page.getByLabel('Mortgage application ID').fill(applicationId)
  await page.getByRole('button', { name: 'Find approved discount', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('No current approved discount')
  expect(consoleErrors).toEqual([])
})

test('request lookup errors, role restrictions, filtering and mobile navigation', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Open request', exact: true }).click()
  await page.getByLabel('Request ID', { exact: true }).fill(crypto.randomUUID())
  await page.getByRole('dialog').getByRole('button', { name: 'Open request', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('not found')
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await page.getByLabel('Demo role').selectOption('22222222-2222-2222-2222-222222222222')
  await expect(page.getByRole('button', { name: 'New request', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Approved discounts', exact: true }).click()
  await expect(page.getByText('Switch the demo role to')).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await page.getByRole('button', { name: 'Pricing exceptions', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Pricing exceptions', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Approved', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Approved', exact: true })).toHaveAttribute('aria-pressed', 'true')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
})

test('desktop and mobile empty workspaces remain accessible', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('Your next exception starts here')).toBeVisible()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.screenshot({ path: 'test-results/workspace-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'New request', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.locator('.sidebar')).not.toBeInViewport()
  await page.screenshot({ path: 'test-results/workspace-mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
})
